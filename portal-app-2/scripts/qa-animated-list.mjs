import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'

const browser = await chromium.launch({ channel: 'chrome' })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.QA_BASE_URL || 'http://127.0.0.1:5180/', { waitUntil: 'networkidle' })
  await page.evaluate(() => localStorage.clear())
  await page.reload({ waitUntil: 'networkidle' })
  const trigger = page.getByRole('button', { name: /ORDERING FOR/ })
  const list = page.getByRole('listbox', { name: 'Choose ordering location' })
  const search = page.getByRole('textbox', { name: 'Search locations' })
  await page.getByRole('button', { name: 'Add All-purpose cleaner to cart', exact: true }).click()
  await trigger.click()
  await search.fill('CW-024')
  assert.equal(await list.getByRole('option').count(), 1)
  await page.keyboard.press('ArrowDown')
  assert.equal(await list.evaluate(el => el === document.activeElement), true)
  await page.keyboard.press('Enter')
  assert.match(await trigger.textContent(), /Orlando/)
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true)
  assert.match(await page.getByRole('button', { name: /Location cart,/ }).getAttribute('aria-label'), /0 units/)
  await trigger.click()
  assert.equal(await search.inputValue(), '')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Home')
  // Browsing never changes the ordering location until activation.
  assert.match(await trigger.textContent(), /Orlando/)
  await page.keyboard.press(' ')
  assert.match(await trigger.textContent(), /Tampa/)
  assert.match(await page.getByRole('button', { name: /Location cart,/ }).getAttribute('aria-label'), /1 units/)
  await trigger.click()
  await search.fill('Jacksonville')
  await search.fill('no match')
  await page.getByRole('status').filter({ hasText: 'No matching locations.' }).waitFor()
  assert.equal(await list.getByRole('option').count(), 0)
  await search.fill('Orlando')
  await page.keyboard.press('ArrowDown')
  // Filtering resets navigation to a valid option after an empty result.
  assert.equal(await list.getAttribute('aria-activedescendant'), await list.getByRole('option').getAttribute('id'))
  await page.keyboard.press('Escape')
  assert.equal(await list.count(), 0)
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true)
  for (const theme of ['light', 'dark']) {
    if (await page.locator('.portal').getAttribute('data-theme') !== theme) await page.getByRole('button', { name: 'Dark mode', exact: true }).click()
    for (const width of [1440, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 })
      await trigger.click()
      assert.equal(await list.getByRole('option').count(), 3)
      await page.getByLabel('Current location').waitFor()
      await page.waitForTimeout(400)
      assert.equal(await list.getByRole('option').first().evaluate(el => getComputedStyle(el).opacity), '1')
      const fits = await page.locator('#locations').evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && el.scrollWidth <= el.clientWidth })
      assert.equal(fits, true, `${theme} ${width}px picker overflow`)
      await page.screenshot({ path: `qa/animated-list-${theme}-${width}.png` })
      await list.getByRole('option', { name: /Jacksonville/ }).click()
      assert.match(await trigger.textContent(), /Jacksonville/)
      await trigger.click()
      await list.getByRole('option', { name: /Tampa/ }).click()
    }
  }
  await trigger.click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await search.press('ArrowDown')
  await page.keyboard.press('End')
  await page.waitForTimeout(50)
  const current = await list.getAttribute('aria-activedescendant')
  assert.match(await page.locator(`[id="${current}"]`).textContent(), /Jacksonville/)
  assert.equal(await page.locator(`[id="${current}"]`).evaluate(el => el.style.transform), '')
  await page.keyboard.press('Escape')
  assert.deepEqual(errors, [])
  console.log('Passed: location name/code search, empty results and recovery, arrow/Home/End navigation, Enter/Space activation, Escape and focus restoration, cart isolation, both themes at 1440/390/320px, live reduced-motion changes, and no runtime errors.')
} finally { await browser.close() }
