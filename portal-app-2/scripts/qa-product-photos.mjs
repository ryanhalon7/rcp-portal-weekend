import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'

const browser = await chromium.launch({ channel:'chrome' })
try {
  const page = await browser.newPage({ viewport:{ width:1440,height:1000 } })
  const errors = []
  page.on('pageerror',error => errors.push(error.message))
  const base = process.env.QA_BASE_URL || 'http://127.0.0.1:5183'
  await page.goto(base+'/#/shop?view=grid',{ waitUntil:'networkidle' })
  await page.locator('.catalog-product').first().waitFor()
  const photos = page.locator('.catalog-product .product-photo')
  assert.equal(await photos.count(),6)
  await photos.evaluateAll(images => images.forEach(img => img.loading='eager'))
  await page.waitForFunction(() => [...document.querySelectorAll('.catalog-product img')].every(img => img.complete && img.naturalWidth > 0))
  await photos.evaluateAll(images => Promise.all(images.map(img => img.decode())))
  for (const img of await photos.all()) await img.scrollIntoViewIfNeeded()
  await page.evaluate(() => window.scrollTo(0,0))
  const imageBounds = await photos.evaluateAll(images => images.map(img => ({ image:img.getBoundingClientRect().height, container:img.closest('.catalog-image-link').getBoundingClientRect().height })))
  for (const bounds of imageBounds) assert.ok(bounds.image > 0 && bounds.image <= bounds.container,'Product photos must fit without clipping')
  await page.screenshot({ path:'qa/product-photos-grid.png',fullPage:true })
  await page.getByRole('link',{ name:'All-purpose cleaner',exact:true }).click()
  await page.locator('.product-detail-art img').waitFor()
  await page.waitForFunction(() => document.querySelector('.product-detail-art img')?.naturalWidth > 0)
  await page.screenshot({ path:'qa/product-photo-detail.png',fullPage:true })
  await page.getByRole('button',{ name:'Add All-purpose cleaner to cart',exact:true }).click()
  await page.getByRole('button',{ name:'Review cart',exact:true }).click()
  assert.equal(await page.getByRole('dialog').locator('.product-photo').count(),1)
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width:390,height:844 })
  await page.getByRole('button',{ name:'Dark mode',exact:true }).click()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false)
  await page.screenshot({ path:'qa/product-photo-mobile-dark.png',fullPage:true })
  await page.goto(base+'/#/shop?tab=approval',{ waitUntil:'networkidle' })
  assert.equal(await page.locator('.catalog-product .product-photo').count(),0)
  assert.equal(await page.locator('.catalog-product .catalog-art svg').count(),4)
  await page.route('**/images/apc-1.avif',route => route.abort())
  await page.goto(base+'/#/shop?product=RCP-1001',{ waitUntil:'networkidle' })
  await page.locator('.product-detail-art svg').waitFor()
  assert.equal(await page.locator('.product-detail-art img').count(),0)
  await page.goto(base+'/',{ waitUntil:'networkidle' })
  await page.waitForFunction(() => [...document.querySelectorAll('.product-image img')].some(img => img.complete && img.naturalWidth > 0))
  assert.deepEqual(errors,[])
  console.log('Passed: six grouped product photos load, detail/cart/dashboard reuse, unmatched and broken-image fallbacks, mobile dark layout, no runtime errors.')
} finally { await browser.close() }
