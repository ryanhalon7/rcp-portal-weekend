import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'

const browser = await chromium.launch({ channel:'chrome' })
try {
  const page = await browser.newPage({ viewport:{ width:1440,height:1100 } })
  const errors = []
  page.on('pageerror',error => errors.push(error.message))
  const base = process.env.QA_BASE_URL || 'http://127.0.0.1:5183'
  await page.goto(base+'/#/lists?mode=saved&id=essentials',{ waitUntil:'networkidle' })
  await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
  await page.reload({ waitUntil:'networkidle' })
  await page.getByRole('heading',{ name:'Everyday essentials',exact:true }).waitFor()
  await page.getByRole('button',{ name:'Add 3 products to cart',exact:true }).waitFor()
  assert.equal(await page.locator('.lists-item-check input:checked').count(),3)
  await page.getByRole('checkbox',{ name:'Include all available',exact:true }).uncheck()
  assert.equal(await page.getByRole('button',{ name:'Choose products to add',exact:true }).isDisabled(),true)
  await page.getByText('Check a product below to include it in your order.',{ exact:true }).waitFor()
  await page.getByRole('checkbox',{ name:'Select All-purpose cleaner',exact:true }).check()
  await page.getByRole('button',{ name:'Add 1 product to cart',exact:true }).waitFor()
  await page.getByRole('checkbox',{ name:'Select Microfiber detailing towels',exact:true }).check()
  await page.getByRole('spinbutton',{ name:'All-purpose cleaner quantity',exact:true }).fill('2')
  const origin = page.url()
  const productLink = page.getByRole('link',{ name:'View All-purpose cleaner details',exact:true })
  await productLink.locator('.lists-item-art').click()
  await page.getByRole('heading',{ name:'All-purpose cleaner',level:1,exact:true }).waitFor()
  await page.reload({ waitUntil:'networkidle' })
  await page.getByRole('heading',{ name:'All-purpose cleaner',level:1,exact:true }).waitFor()
  await page.locator('.pack-options a').filter({ hasText:'5 gallon' }).click()
  await page.getByRole('heading',{ name:/All-purpose cleaner.*bulk/,level:1 }).waitFor()
  await page.getByRole('link',{ name:'Back to your list',exact:true }).click()
  await page.getByRole('heading',{ name:'Everyday essentials',exact:true }).waitFor()
  assert.equal(page.url(),origin)
  assert.equal(await page.getByRole('spinbutton',{ name:'All-purpose cleaner quantity',exact:true }).inputValue(),'2')
  assert.equal(await page.getByRole('checkbox',{ name:'Select Wash & wax concentrate',exact:true }).isChecked(),false)
  await page.getByRole('button',{ name:'Add 2 products to cart',exact:true }).waitFor()
  await page.getByRole('button',{ name:'Add 2 products to cart',exact:true }).click()
  const cart = page.getByRole('dialog',{ name:'Location cart',exact:true })
  await cart.waitFor()
  assert.equal(await cart.locator('.cart-item').count(),2)
  assert.equal(await cart.locator('.cart-total strong').textContent(),'$152.00')
  await page.keyboard.press('Escape')
  await page.goto(base+'/#/lists?mode=orders&id=10435',{ waitUntil:'networkidle' })
  await page.getByRole('link',{ name:'View Non-acid wheel cleaner details',exact:true }).click()
  await page.getByRole('heading',{ name:'Non-acid wheel cleaner',level:1,exact:true }).waitFor()
  await page.getByRole('link',{ name:'Back to your list',exact:true }).click()
  await page.getByRole('heading',{ name:'Order #10435',exact:true }).waitFor()
  assert.equal(await page.getByRole('tab',{ name:'Past orders',exact:true }).getAttribute('aria-selected'),'true')
  await page.goto(base+'/#/lists?mode=saved&id=wash-bay',{ waitUntil:'networkidle' })
  await page.getByRole('link',{ name:'View Vehicle wash concentrate details',exact:true }).click()
  await page.getByRole('heading',{ name:'Vehicle wash concentrate',level:1,exact:true }).waitFor()
  assert.equal(await page.getByRole('button',{ name:'Add Vehicle wash concentrate to cart',exact:true }).isDisabled(),true)
  await page.goBack()
  await page.getByRole('heading',{ name:'Wash bay supplies',exact:true }).waitFor()
  assert.equal(await page.getByRole('checkbox',{ name:'Select Vehicle wash concentrate',exact:true }).isChecked(),false)
  for (const theme of ['light','dark']) {
    if (await page.locator('.portal').getAttribute('data-theme') !== theme) await page.getByRole('button',{ name:'Dark mode',exact:true }).click()
    for (const width of [1440,1280,1024,768,600,540,390,320]) {
      await page.setViewportSize({ width,height:1000 })
      await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth)
      assert.equal(await page.locator('.lists-review').evaluate(el => el.scrollWidth > el.clientWidth),false,`${theme} ${width}: review overflow`)
      if ([1440,390].includes(width)) await page.screenshot({ path:`qa/lists-refined-${theme}-${width}.png`,fullPage:true })
    }
  }
  // Back links accept only the internal Lists route, even when the URL is edited.
  await page.goto(base+'/#/shop?product=RCP-1001&returnTo='+encodeURIComponent('https://example.com'),{ waitUntil:'networkidle' })
  await page.getByRole('link',{ name:'Back to your catalog',exact:true }).waitFor()
  assert.equal(await page.getByRole('link',{ name:'Back to your list',exact:true }).count(),0)
  assert.deepEqual(errors,[])
  console.log('Passed: explicit inclusion/counts, zero-selection recovery, photo/name PDP links, list/order/variant return routes, saved draft quantities/selections, exact cart lines/totals, unavailable item blocked, both themes at eight widths, internal return validation, no runtime errors.')
} finally { await browser.close() }
