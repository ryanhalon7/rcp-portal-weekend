import { chromium } from 'playwright-core'
import { mkdirSync, writeFileSync } from 'node:fs'
import assert from 'node:assert/strict'

mkdirSync('qa', { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 })
const errors = []
page.setDefaultTimeout(12000)
await page.emulateMedia({ reducedMotion: 'reduce' })
page.on('pageerror', error => errors.push(error.message))
await page.goto(process.env.QA_BASE_URL || 'http://127.0.0.1:5184', { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.reload({ waitUntil: 'networkidle' })
await page.screenshot({ path: 'qa/home-desktop.png', fullPage: true })
assert.match(await page.locator('h1').textContent(), /Good morning, Jamie/)
await page.getByRole('button', { name: 'Add All-purpose cleaner to cart', exact: true }).click()
assert.match(await page.getByRole('button', { name: /Location cart,/ }).getAttribute('aria-label'), /1 units, \$64.00/)
await page.getByRole('button', { name: /ORDERING FOR/ }).click()
await page.getByRole('button', { name: 'Orlando, FL', exact: true }).click()
assert.match(await page.getByRole('button', { name: /Location cart,/ }).getAttribute('aria-label'), /0 units/)
await page.getByRole('button', { name: /ORDERING FOR/ }).click()
await page.getByRole('button', { name: 'Tampa, FL', exact: true }).click()
await page.reload({ waitUntil: 'networkidle' })
assert.match(await page.getByRole('button', { name: /Location cart,/ }).getAttribute('aria-label'), /1 units/)
await page.getByRole('button', { name: 'Quick order', exact: true }).click()
await page.getByLabel('SKU, quantity').fill('BAD,2\nRCP-1001,0')
await page.getByRole('button', { name: 'Add to location cart', exact: true }).click()
await page.getByRole('alert').waitFor()
assert.match(await page.getByRole('button', { name: /Location cart,/ }).getAttribute('aria-label'), /1 units/)
await page.getByLabel('SKU, quantity').fill('RCP-1001,2\nRCP-1001,1\nRCP-3102,2')
await page.getByRole('button', { name: 'Add to location cart', exact: true }).click()
await page.getByRole('dialog').getByText('$304.00', { exact: true }).waitFor()
await page.screenshot({ path: 'qa/cart-desktop.png', fullPage: true })
await page.keyboard.press('Escape')
assert.equal(await page.getByRole('dialog').count(), 0)
await page.getByRole('tab', { name: 'Bay essentials' }).click()
assert.equal(await page.locator('.product-row').count(), 3)
await page.getByLabel('Search products or SKU').fill('nonexistent')
await page.getByText('No matching products', { exact: true }).waitFor()
await page.getByRole('button', { name: 'Clear search', exact: true }).click()
await page.getByRole('tab', { name: 'Frequently ordered' }).click()
await page.getByRole('button', { name: 'Previous month', exact: true }).click()
assert.match(await page.locator('.spend-amount').textContent(), /6,120/)
await page.getByRole('button', { name: 'Next month', exact: true }).click()
await page.getByRole('button', { name: 'View available credit', exact: true }).click()
await page.getByRole('dialog').getByText('$18,450.00', { exact: true }).waitFor()
await page.keyboard.press('Escape')
await page.getByRole('button', { name: /#10528/ }).click()
await page.getByRole('button', { name: 'Reorder these items', exact: true }).click()
await page.getByRole('dialog').getByText('Your location cart', { exact: true }).waitFor()
await page.keyboard.press('Escape')
const geometry = []
await page.getByRole('button', { name: 'Dismiss notification', exact: true }).click()
await page.locator('h1').click()
for (const width of [1920, 1440, 1280, 1024, 768, 540, 390, 358, 320]) {
  await page.setViewportSize({ width, height: 1000 })
  await page.evaluate(() => window.scrollTo(0,0))
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  geometry.push({ width, overflow })
  assert.equal(overflow, false, `Horizontal overflow at ${width}`)
  if ([1440,390,320].includes(width)) await page.screenshot({ path: `qa/home-${width}.png`, fullPage: true })
}
await page.setViewportSize({ width: 390, height: 844 })
await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
await page.screenshot({ path: 'qa/navigation-mobile.png', fullPage: true })
await page.getByRole('button', { name: 'Close navigation', exact: true }).click()
await page.getByRole('button', { name: 'Quick order', exact: true }).click()
await page.screenshot({ path: 'qa/quick-order-mobile.png', fullPage: true })
await page.keyboard.press('Escape')
assert.deepEqual(errors, [])
writeFileSync('qa/results.json', JSON.stringify({ errors, geometry, checks: ['cart persistence', 'location separation', 'quick order validation', 'duplicate SKU merge', 'saved list', 'empty search', 'month switch', 'credit details', 'reorder', 'mobile navigation'] }, null, 2))
await browser.close()
console.log('Dashboard QA passed: interactions, responsive widths, and no runtime errors.')
