const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 })
const errors = []
page.on('pageerror', e => errors.push(e.message))
await page.goto(process.env.QA_BASE_URL || 'http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.evaluate(() => { localStorage.clear() })
await page.reload({ waitUntil: 'networkidle' })
await page.screenshot({ path: 'qa/dashboard-desktop.png', fullPage: true })
assert.equal(await page.locator('h1').textContent(), 'Let’s keep things moving.')
await page.getByRole('button', { name: 'Add All-purpose cleaner to cart', exact: true }).click()
await page.getByRole('button', { name: /Location cart, 1 units/ }).click()
await page.getByRole('dialog').getByText('$64.00', { exact: true }).first().waitFor()
await page.getByRole('button', { name: 'Close dialog' }).click()
await page.getByRole('button', { name: /ORDERING FOR/ }).click()
await page.getByRole('option', { name: /Orlando, FL/ }).click()
assert.match(await page.getByRole('button', { name: /Location cart,/ }).getAttribute('aria-label'), /0 units/)
await page.getByRole('button', { name: /ORDERING FOR/ }).click()
await page.getByRole('option', { name: /Tampa, FL/ }).click()
assert.match(await page.getByRole('button', { name: /Location cart,/ }).getAttribute('aria-label'), /1 units/)
await page.reload({ waitUntil: 'networkidle' })
